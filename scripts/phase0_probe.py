"""Phase 0 (spec 17): measures the assumptions V1-V5, V8 and V11 and writes docs/PHASE0.md.

    python scripts/phase0_probe.py

V8 (an AMR-NB encoder in ffmpeg) and V11 (fdatasync latency of the volume that holds audit/ and ledger.db) need no account. V4 (Timbre) and V5 (Prisma
fields) make a handful of real calls and run only when GNANI_API_KEY is set; without it the rows say so instead of guessing."""

import asyncio
import os
import statistics
import subprocess
import tempfile
import time
from pathlib import Path

from lexi.adapters.cache import ProviderCache
from lexi.adapters.prisma import PrismaClient
from lexi.adapters.timbre import TimbreClient
from lexi.cli import ROOT, load_runtime
from lexi.common.errors import ProviderError
from lexi.common.types import TtsRequest

PROBE_TEXT = {"hi": "शर्मा जी का पैंतीस हज़ार आया है", "ta": "ஷர்மா ஜி முப்பத்தைந்தாயிரம் வந்தது"}


def fsync_ms(directory: Path, n: int = 500) -> list[float]:
    """V11: one 4 KiB append plus fdatasync, the cost of one audit group commit."""
    out = []
    with tempfile.NamedTemporaryFile(dir=directory) as f:
        for _ in range(n):
            t0 = time.perf_counter()
            f.write(b"x" * 4096)
            f.flush()
            os.fdatasync(f.fileno())
            out.append((time.perf_counter() - t0) * 1000)
    return out


def amr_encoder() -> bool:
    """V8."""
    try:
        r = subprocess.run(["ffmpeg", "-hide_banner", "-encoders"], capture_output=True, text=True, check=False)
    except FileNotFoundError:
        return False
    return "amr_nb" in r.stdout


async def live_rows(cfg: dict) -> list[str]:
    """V4 and V5 on the real endpoints: Timbre voices and latency, then what Prisma returns for that audio."""
    cache = ProviderCache(ROOT / cfg["paths"]["providers_cache"], "live")
    timbre, prisma = TimbreClient("live", cfg["providers"]["timbre"], cache), PrismaClient("live", cfg["providers"]["prisma"], cache)
    rows = []
    for lang, voices in cfg["providers"]["timbre"]["voices"].items():
        for voice in voices:
            t0 = time.perf_counter()
            try:
                audio = await timbre.synth(TtsRequest(text=PROBE_TEXT[lang], lang=lang, voice=voice))
            except ProviderError as e:
                rows.append(f"| V4 Timbre {lang}/{voice} | failed: {e} |")
                continue
            rows.append(f"| V4 Timbre {lang}/{voice} | {audio.duration_ms / 1000:.1f} s of audio in {time.perf_counter() - t0:.2f} s (full response; first-chunk latency not split out) |")
            if lang != "hi" or voice != voices[0]:
                continue
            session = await prisma.open("phase0", lang)
            for i in range(0, len(audio.pcm_s16le) - 319, 320):
                await session.feed(audio.pcm_s16le[i:i + 320], i // 16)
            await asyncio.sleep(4)
            events = session.poll()
            await session.close()
            words = [w for e in events for w in e.words]
            rows.append(f"| V5 Prisma fields | {len(events)} events, {len(words)} words, word confidence {'present' if any(w.conf is not None for w in words) else 'ABSENT'}, "
                        f"transcript: {' '.join(e.text for e in events if e.kind == 'final')!r} |")
    return rows


def main() -> None:
    cfg = load_runtime()
    data = ROOT / cfg["paths"]["data"]
    data.mkdir(exist_ok=True)
    ms = sorted(fsync_ms(data))
    p50, p99 = statistics.median(ms), ms[int(len(ms) * 0.99) - 1]
    rows = [f"| V11 fdatasync of 4 KiB | p50 {p50:.2f} ms, p99 {p99:.2f} ms over {len(ms)} writes on {data} (target p99 <= 3 ms: {'met' if p99 <= 3 else 'NOT met, tune audit.group_commit_ms and restate L3'}) |",
            f"| V8 AMR-NB encoder in ffmpeg | {'available' if amr_encoder() else 'missing: the channel simulator falls back to G.711 mu-law plus loss'} |"]
    if os.environ.get(cfg["providers"]["timbre"]["key_env"]):
        rows += asyncio.run(live_rows(cfg))
    else:
        rows += [f"| V4 Timbre, V5 Prisma fields | not measured: {cfg['providers']['timbre']['key_env']} is not set; the system runs on the simulators (docs/DECISIONS.md D-001) |"]
    (ROOT / "docs" / "PHASE0.md").write_text(
        "# Phase 0 measurements\n\nGenerated by `python scripts/phase0_probe.py`. Re-run it after adding keys to `.env`.\n\n| assumption | measured |\n|---|---|\n"
        + "\n".join(rows) + f"\n\nMeasured {time.strftime('%Y-%m-%d %H:%M')} on {os.uname().sysname} {os.uname().release}.\n", encoding="utf-8")
    print("\n".join(rows))


if __name__ == "__main__":
    main()
